// Bundles src/liveness-web/main.tsx into a single self-contained HTML string
// module (src/generated/livenessHtml.ts) that the app ships inside the APK
// and loads into a WebView — no page hosting needed. Run after changing the
// page: npm run build:liveness-web
import esbuild from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';

const result = await esbuild.build({
  entryPoints: ['src/liveness-web/main.tsx'],
  bundle: true,
  minify: true,
  write: false,
  outdir: 'dist-liveness',
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"', global: 'window' },
  loader: { '.svg': 'dataurl', '.png': 'dataurl', '.woff': 'dataurl', '.woff2': 'dataurl' },
  logLevel: 'warning',
});

let js = '';
let css = '';
for (const file of result.outputFiles) {
  if (file.path.endsWith('.js')) js = file.text;
  if (file.path.endsWith('.css')) css = file.text;
}
if (!js) throw new Error('esbuild produced no JS output');

// A literal "</script>" inside the bundle would terminate the inline tag.
js = js.replaceAll('</script', '<\\/script');

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>
html,body{margin:0;padding:0;height:100%;background:#12161C;overflow-y:auto;-webkit-overflow-scrolling:touch}
/* min-height (not height) lets the AWS start screen grow past one viewport
   and scroll instead of clipping its start button on short/wide screens. */
#root{min-height:100%;display:flex;flex-direction:column;justify-content:center}
#root>*{width:100%}
</style>
<style>${css}</style>
</head>
<body>
<div id="root"></div>
<script>window.__CONFIG__={sessionId:"__SESSION_ID__",region:"__REGION__",identityPoolId:"__IDENTITY_POOL_ID__"};</script>
<script>${js}</script>
</body>
</html>`;

mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/livenessHtml.ts',
  `// GENERATED by scripts/build-liveness-web.mjs — do not edit by hand.
// Self-contained AWS Face Liveness page; the verify screen substitutes the
// __SESSION_ID__ / __REGION__ / __IDENTITY_POOL_ID__ placeholders at runtime.
export const LIVENESS_HTML: string = ${JSON.stringify(html)};
`,
);
console.log(`liveness page bundled: ${(html.length / 1024).toFixed(0)} KB`);
